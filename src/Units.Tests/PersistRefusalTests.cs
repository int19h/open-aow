    [Fact]
    public void EngineClassesOutsideThePersistenceTreeAreRefused()
    {
        var found = new List<string>();
        foreach (var eclass in EClass.All)
        {
            if (eclass.Type.Assembly != typeof(TEObject).Assembly) continue;
            if (TEObject.TreePersistenceRefusal(eclass.Type) is string) found.Add(eclass.Type.Name);
        }
        found.Sort(static (a, b) => string.CompareOrdinal(a, b));
        var expected = Refused.ToList();
        expected.Sort(static (a, b) => string.CompareOrdinal(a, b));
        var missing = expected.Except(found).ToArray();
        var extra = found.Except(expected).ToArray();
        Assert.True(missing.Length == 0 && extra.Length == 0,
            "Refused list is missing " + string.Join(", ", missing) + " and has extra " + string.Join(", ", extra) + ".");
        Assert.Equal(expected, found);
        Assert.Null(TEObject.TreePersistenceRefusal(typeof(TEnchantment)));
        Assert.Null(TEObject.TreePersistenceRefusal(typeof(TEChangeNotifyNode)));
        Assert.Null(TEObject.TreePersistenceRefusal(typeof(TUnitList)));
        Assert.Null(TEObject.TreePersistenceRefusal(typeof(TArmyView)));
        using var list = new TEventLogList(null!);
        var error = Assert.Throws<InvalidOperationException>(() => TreeWriter.Write(list, new EnginePersistableFactory(EngineFixture.Engine)));
        Assert.Equal("Class TEventLogList overrides MainReadWrite or ReadWriteChildren and has no MainPersist.", error.Message);
    }
